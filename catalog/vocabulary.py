"""Render the capability vocabulary (capability_definitions) as Markdown for the data standard."""

from __future__ import annotations

import re

import psycopg

START = "<!-- vocabulary:start (generated by scripts/data_standard.py; do not edit by hand) -->"
END = "<!-- vocabulary:end -->"

TYPE_TEXT = {
    "boolean": "`true` or `false`",
    "number": "a number",
    "text": "a string",
    "text_list": "a non-empty list of distinct strings",
    "object": "a JSON object",
}


def fetch_definitions(conn: psycopg.Connection) -> list[dict]:
    with conn.cursor(row_factory=psycopg.rows.dict_row) as cur:
        cur.execute(
            "select name, value_type, description, allowed_values, value_format, unit"
            " from capability_definitions order by name"
        )
        return cur.fetchall()


def render(definitions: list[dict]) -> str:
    lines = [START, "", "| Name | Value | Rules | Meaning |", "| --- | --- | --- | --- |"]
    for d in definitions:
        rules = []
        if d["value_format"] == "language_code":
            rules.append("ISO 639-1 two-letter codes, lowercase (`hi`, `en`)")
        if d["allowed_values"]:
            rules.append("one of " + ", ".join(f"`{v}`" for v in d["allowed_values"]))
        if d["unit"]:
            rules.append(f"unit: {d['unit']}")
        cells = [f"`{d['name']}`", TYPE_TEXT[d["value_type"]], "; ".join(rules) or "-", d["description"]]
        lines.append("| " + " | ".join(c.replace("|", "\\|").replace("\n", " ") for c in cells) + " |")
    lines += ["", END]
    return "\n".join(lines)


def replace_section(document: str, section: str) -> str:
    pattern = re.compile(re.escape(START) + ".*?" + re.escape(END), re.S)
    if not pattern.search(document):
        raise ValueError("vocabulary markers not found in document")
    return pattern.sub(lambda _: section, document)
